"""Pillar 3 — Dual-Readable Handbook Compiler (design doc §5.1–§5.4).

Compiles ACTIVE ``PERSISTENT`` OKF knowledge nodes into a human-browsable +
AI-readable Markdown handbook under ``<runtime base>/handbook/``::

    handbook/
    ├── INDEX.md / README.md              # global table of contents
    └── <project>/
        ├── README.md                     # project overview + top takeaways
        ├── pitfalls-and-caveats.md       # all okf_type == pitfall nodes
        ├── architecture-decisions.md     # all okf_type == decision nodes
        └── notes/<clean-slug>.md         # one page per fact/procedure node

The output is a pure compilation product: every generated file carries the
``HANDBOOK_GENERATED_MARK`` banner, ``build_handbook`` is idempotent, and the
whole tree can be ``rm -rf``'d and rebuilt from the SQLite store alone
(§5.4 acceptance (iii)).
"""

from __future__ import annotations

import os
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

from synapse.config import SynapseConfig
from synapse.models import (
    FALLBACK_PROJECT as _FALLBACK_PROJECT,
    Node,
    NodeStatus,
    NodeType,
    clean_slug,
    infer_project,
    normalize_project_slug,
    project_domains,
)
from synapse.okf import _split_sections
from synapse.okf.transcripts import is_session_transcript
from synapse.storage import SQLiteNodeStore
from synapse.utils.runtime import RuntimePaths

HANDBOOK_GENERATED_MARK = "<!-- GENERATED BY SYNAPSE HANDBOOK — DO NOT EDIT MANUALLY -->"

HUB_TAG = "dreamer-hub"

_PITFALL_SECTIONS = ("Symptom", "Cause", "Fix")
_DECISION_SECTIONS = ("Context", "Decision", "Consequences")


def _takeaway(node: Node, sections: dict[str, str]) -> str:
    """OKF takeaway = first non-empty line of ``## Takeaway``; title fallback."""

    for line in sections.get("Takeaway", "").splitlines():
        stripped = line.strip()
        if stripped:
            return stripped
    return node.title


def _sources(node: Node) -> list[str]:
    return [source for source in node.metadata.sources if source]


def _source_links(sources: list[str]) -> str:
    if not sources:
        return "_no sources_"
    return " · ".join(f"`{source}`" for source in sources)


def _escape_row(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def _knowledge_nodes(store: SQLiteNodeStore) -> list[Node]:
    """ACTIVE persistent knowledge nodes, minus transcripts and falsified nodes."""

    rows = store.connection.execute(
        "SELECT * FROM nodes WHERE type = ? AND status = ? ORDER BY id",
        (NodeType.PERSISTENT.value, NodeStatus.ACTIVE.value),
    ).fetchall()
    nodes: list[Node] = []
    for row in rows:
        node = store._row_to_node(row)  # noqa: SLF001 — same-package derived-index read
        if is_session_transcript(node):
            continue
        if node.metadata.verified is False:
            continue
        nodes.append(node)
    return nodes


def _sorted_pitfalls(nodes: list[Node]) -> list[Node]:
    return sorted(nodes, key=lambda n: (-len(_sources(n)), -n.metadata.access_count, n.id))


def _sorted_decisions(nodes: list[Node]) -> list[Node]:
    return sorted(nodes, key=lambda n: (-len(_sources(n)), n.id))


def _multi_source(nodes: list[Node]) -> list[Node]:
    return sorted(
        (node for node in nodes if len(_sources(node)) >= 2),
        key=lambda n: (-len(_sources(n)), -n.metadata.access_count, n.id),
    )


def resolve_project_slug(raw_project: str) -> str:
    """Resolve a workspace directory or project name to its canonical handbook slug."""

    slug = normalize_project_slug(raw_project)
    if slug == _FALLBACK_PROJECT:
        return _FALLBACK_PROJECT
    low = raw_project.strip().lower()
    for domain_slug, markers in project_domains():
        if slug == domain_slug or any(marker in low for marker in markers):
            return domain_slug
    return slug


def project_top_takeaways(
    store: SQLiteNodeStore,
    project: str,
    *,
    limit: int = 6,
) -> dict[str, Any]:
    """Return top corroborated/high-utility takeaways for *project* (session header index)."""

    target_project = resolve_project_slug(project)
    capped_limit = max(1, min(int(limit), 20))
    matched = [
        node
        for node in _knowledge_nodes(store)
        if infer_project(node) == target_project
    ]
    multi = _multi_source(matched)
    multi_ids = {node.id for node in multi}
    single = sorted(
        (node for node in matched if node.id not in multi_ids),
        key=lambda n: (-n.metadata.used_count, -n.metadata.access_count, n.id),
    )
    selected = (multi + single)[:capped_limit]
    items: list[dict[str, Any]] = []
    for node in selected:
        sections = _split_sections(node.content)
        items.append(
            {
                "node_id": node.id,
                "title": node.title,
                "okf_type": node.metadata.okf_type or "fact",
                "takeaway": _takeaway(node, sections),
                "sources_count": len(_sources(node)),
            }
        )
    return {
        "project": target_project,
        "total_nodes": len(matched),
        "items": items,
    }

def _page_link(node: Node, okf_type: str) -> str:
    if okf_type in {"fact", "procedure"}:
        return f"notes/{clean_slug(node.id)}.md"
    if okf_type == "pitfall":
        return "pitfalls-and-caveats.md"
    if okf_type == "decision":
        return "architecture-decisions.md"
    return ""


def _takeaways_table(nodes: list[Node]) -> list[str]:
    lines = ["| Takeaway | Type | Sources | Node |", "|---|---|---:|---|"]
    for node in nodes:
        sections = _split_sections(node.content)
        okf_type = node.metadata.okf_type or "untyped"
        page = _page_link(node, okf_type)
        node_cell = f"[`{clean_slug(node.id)}`]({page})" if page else f"`{node.id}`"
        lines.append(
            f"| {_escape_row(_takeaway(node, sections))} | `{okf_type}` | {len(_sources(node))} | {node_cell} |"
        )
    return lines


def _node_identity_block(node: Node) -> list[str]:
    return ["", f"`{node.id}` · access_count: {node.metadata.access_count}", ""]


def _render_pitfall_entry(node: Node, sections: dict[str, str]) -> list[str]:
    lines = [f"### {node.title}", "", f"> **Takeaway:** {_takeaway(node, sections)}", ""]
    for section in _PITFALL_SECTIONS:
        body = sections.get(section, "").strip()
        if body:
            lines.extend([f"**{section}:**", "", body, ""])
    lines.append(f"**Sources:** {_source_links(_sources(node))}")
    lines.extend(_node_identity_block(node))
    return lines


def _render_decision_entry(node: Node, sections: dict[str, str]) -> list[str]:
    lines = [f"### {node.title}", "", f"> **Takeaway:** {_takeaway(node, sections)}", ""]
    for section in _DECISION_SECTIONS:
        body = sections.get(section, "").strip()
        if body:
            lines.extend([f"**{section}:**", "", body, ""])
    lines.append(f"**Sources:** {_source_links(_sources(node))}")
    lines.extend(_node_identity_block(node))
    return lines


def _render_note_page(node: Node, sections: dict[str, str]) -> str:
    okf_type = node.metadata.okf_type or "note"
    lines = [
        HANDBOOK_GENERATED_MARK,
        "",
        f"# {node.title}",
        "",
        f"> **OKF:** `{okf_type}` · **Sources:** {_source_links(_sources(node))}",
        "",
        f"**Takeaway:** {_takeaway(node, sections)}",
        "",
    ]
    # Render every body section verbatim except Takeaway/Sources (header holds them).
    for heading, body in sections.items():
        if heading in {"Takeaway", "Sources"} or not body:
            continue
        lines.extend([f"## {heading}", "", body, ""])
    lines.append("---")
    lines.extend(_node_identity_block(node))
    return "\n".join(lines)


def _pitfalls_page(project: str, nodes: list[Node]) -> str:
    ordered = _sorted_pitfalls(nodes)
    lines = [
        HANDBOOK_GENERATED_MARK,
        "",
        f"# {project} — Pitfalls & Caveats",
        "",
        f"_{len(ordered)} recorded pitfalls, most-corroborated first (sources desc, then "
        f"access_count desc). Find every known trap of this project here without reading a transcript._",
        "",
    ]
    if not ordered:
        lines.append("_No pitfalls recorded._")
        lines.append("")
    for node in ordered:
        lines.extend(_render_pitfall_entry(node, _split_sections(node.content)))
    return "\n".join(lines) + "\n"


def _decisions_page(project: str, nodes: list[Node]) -> str:
    ordered = _sorted_decisions(nodes)
    lines = [
        HANDBOOK_GENERATED_MARK,
        "",
        f"# {project} — Architecture Decisions",
        "",
        f"_{len(ordered)} recorded decisions, most-corroborated first (sources desc)._",
        "",
    ]
    if not ordered:
        lines.append("_No decisions recorded._")
        lines.append("")
    for node in ordered:
        lines.extend(_render_decision_entry(node, _split_sections(node.content)))
    return "\n".join(lines) + "\n"


def _project_readme(project: str, by_type: dict[str, list[Node]], generated_at: str) -> str:
    all_nodes = [node for bucket in by_type.values() for node in bucket]
    highlights = _multi_source(all_nodes)[:10]
    if not highlights:
        highlights = sorted(all_nodes, key=lambda n: (-n.metadata.access_count, n.id))[:10]
    facts_and_procedures = len(by_type.get("fact", [])) + len(by_type.get("procedure", []))
    hub_count = sum(1 for node in all_nodes if HUB_TAG in node.metadata.tags)

    lines = [
        HANDBOOK_GENERATED_MARK,
        "",
        f"# {project} — Handbook",
        "",
        f"_Compiled {generated_at} by `synapse handbook build`. "
        "This file is generated output — regenerate instead of editing._",
        "",
        "## Overview",
        "",
        f"- Knowledge nodes: **{len(all_nodes)}**",
        f"- Pitfalls: {len(by_type.get('pitfall', []))} · Decisions: {len(by_type.get('decision', []))} "
        f"· Facts & procedures: {facts_and_procedures}",
    ]
    for okf_type in sorted(by_type):
        lines.append(f"- `{okf_type}`: {len(by_type[okf_type])}")
    if hub_count:
        lines.append(f"- L3 hub (MOC) nodes: {hub_count}")
    lines.extend(
        [
            "",
            "## Top Multi-Source / High-Utility Takeaways",
            "",
            "_Multi-source consolidated nodes first; single-source projects fall back to "
            "the most-accessed nodes._",
            "",
        ]
    )
    if highlights:
        lines.extend(_takeaways_table(highlights))
    else:
        lines.append("_No knowledge nodes._")
    lines.extend(
        [
            "",
            "## Navigation",
            "",
            f"- [Pitfalls & Caveats](pitfalls-and-caveats.md) — {len(by_type.get('pitfall', []))} entries",
            f"- [Architecture Decisions](architecture-decisions.md) — {len(by_type.get('decision', []))} entries",
            f"- `notes/` — {facts_and_procedures} fact/procedure pages",
            "- [Global index](../INDEX.md)",
            "",
        ]
    )
    return "\n".join(lines) + "\n"


def _global_index(
    projects: dict[str, dict[str, list[Node]]],
    project_by_node: dict[str, str],
    *,
    generated_at: str,
) -> str:
    totals = {"total": 0, "pitfall": 0, "decision": 0, "fact": 0, "procedure": 0}
    all_nodes: list[Node] = []
    for by_type in projects.values():
        for okf_type, bucket in by_type.items():
            totals["total"] += len(bucket)
            if okf_type in totals:
                totals[okf_type] += len(bucket)
            all_nodes.extend(bucket)
    highlights = _multi_source(all_nodes)[:15]

    lines = [
        HANDBOOK_GENERATED_MARK,
        "",
        "# Synapse Handbook — Index",
        "",
        f"_Compiled {generated_at} by `synapse handbook build` from ACTIVE persistent OKF "
        "knowledge nodes._",
        "",
        "## Projects",
        "",
        "| Project | Total | Pitfalls & Caveats | Decisions | Facts & Procedures |",
        "|---|---:|---:|---:|---:|",
    ]
    for project in sorted(projects):
        by_type = projects[project]
        facts_and_procedures = len(by_type.get("fact", [])) + len(by_type.get("procedure", []))
        lines.append(
            f"| [{project}](./{project}/README.md) | {sum(len(bucket) for bucket in by_type.values())} "
            f"| {len(by_type.get('pitfall', []))} | {len(by_type.get('decision', []))} "
            f"| {facts_and_procedures} |"
        )
    lines.extend(
        [
            "",
            "## Multi-Source Consolidated Highlights",
            "",
            "_Nodes with `len(sources) >= 2` — cross-session knowledge merged by the Dreamer; "
            "the densest entries of the whole handbook._",
            "",
        ]
    )
    if highlights:
        lines.extend(
            [
                "| Takeaway | Project | Type | Sources | Node |",
                "|---|---|---|---:|---|",
            ]
        )
        for node in highlights:
            project = project_by_node.get(node.id, _FALLBACK_PROJECT)
            sections = _split_sections(node.content)
            okf_type = node.metadata.okf_type or "untyped"
            lines.append(
                f"| {_escape_row(_takeaway(node, sections))} | [{project}](./{project}/README.md) "
                f"| `{okf_type}` | {len(_sources(node))} | `{node.id}` |"
            )
    else:
        lines.append("_No multi-source nodes yet — see `synapse stats` (consolidation ratio)._")
    lines.extend(
        [
            "",
            f"Total knowledge nodes: **{totals['total']}** · pitfalls: {totals['pitfall']} · "
            f"decisions: {totals['decision']} · facts & procedures: "
            f"{totals['fact'] + totals['procedure']}",
            "",
        ]
    )
    return "\n".join(lines) + "\n"


def _write_text(path: Path, content: str, files_written: list[str]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")
    files_written.append(str(path))


def _is_generated_file(path: Path) -> bool:
    try:
        with path.open("r", encoding="utf-8") as handle:
            return HANDBOOK_GENERATED_MARK in handle.readline()
    except (OSError, UnicodeDecodeError):
        return False


def _remove_dir_if_empty(path: Path) -> None:
    try:
        next(path.iterdir())
    except StopIteration:
        try:
            path.rmdir()
        except OSError:
            pass
    except OSError:
        pass


def _prune_generated_tree(target: Path) -> None:
    """Delete previous generated files so removed/retired nodes leave no stale pages.

    Only files carrying the generated banner are deleted; hand-written files in
    the output directory are preserved. Directories emptied by the sweep are
    removed bottom-up.
    """

    if not target.exists():
        return
    for root, dirnames, filenames in os.walk(target, topdown=False):
        root_path = Path(root)
        for filename in filenames:
            path = root_path / filename
            if _is_generated_file(path):
                try:
                    path.unlink()
                except OSError:
                    pass
        for dirname in dirnames:
            _remove_dir_if_empty(root_path / dirname)
    _remove_dir_if_empty(target)


def build_handbook(
    config: SynapseConfig,
    runtime_paths: RuntimePaths,
    *,
    out_dir: Path | None = None,
) -> dict[str, Any]:
    """Compile the dual-readable handbook (§5.1–§5.4). Idempotent; read-only on the DB.

    Returns ``{"out_dir", "projects": {project: node_count}, "total_nodes",
    "files_written"}``.
    """

    target = Path(out_dir).expanduser().resolve() if out_dir is not None else runtime_paths.base / "handbook"
    db_path = runtime_paths.base / "synapse.db"
    if not db_path.exists():
        raise FileNotFoundError(f"Synapse SQLite index not found: {db_path}")

    store = SQLiteNodeStore(db_path, embedding_dimension=config.embedding.dimension or 0)
    try:
        nodes = _knowledge_nodes(store)
    finally:
        store.close()

    projects: dict[str, dict[str, list[Node]]] = {}
    project_by_node: dict[str, str] = {}
    for node in nodes:
        project = infer_project(node)
        project_by_node[node.id] = project
        projects.setdefault(project, {}).setdefault(node.metadata.okf_type or "untyped", []).append(node)

    generated_at = datetime.now(UTC).isoformat(timespec="seconds").replace("+00:00", "Z")
    files_written: list[str] = []

    # Cleanup before writing: the handbook is a pure compilation product, so a
    # rebuild must never resurrect pages of deleted or archived-out nodes.
    _prune_generated_tree(target)
    target.mkdir(parents=True, exist_ok=True)

    for project, by_type in sorted(projects.items()):
        project_dir = target / project
        notes_dir = project_dir / "notes"

        used_slugs: set[str] = set()
        for okf_type in ("fact", "procedure"):
            for node in sorted(
                by_type.get(okf_type, []), key=lambda n: (-len(_sources(n)), -n.metadata.access_count, n.id)
            ):
                slug = clean_slug(node.id)
                if slug in used_slugs:
                    suffix = 2
                    while f"{slug}-{suffix}" in used_slugs:
                        suffix += 1
                    slug = f"{slug}-{suffix}"
                used_slugs.add(slug)
                _write_text(
                    notes_dir / f"{slug}.md",
                    _render_note_page(node, _split_sections(node.content)),
                    files_written,
                )

        notes_dir.mkdir(parents=True, exist_ok=True)
        _write_text(project_dir / "pitfalls-and-caveats.md", _pitfalls_page(project, by_type.get("pitfall", [])), files_written)
        _write_text(project_dir / "architecture-decisions.md", _decisions_page(project, by_type.get("decision", [])), files_written)
        _write_text(project_dir / "README.md", _project_readme(project, by_type, generated_at), files_written)

    index_content = _global_index(projects, project_by_node, generated_at=generated_at)
    _write_text(target / "INDEX.md", index_content, files_written)
    _write_text(target / "README.md", index_content, files_written)

    return {
        "out_dir": str(target),
        "projects": {
            project: sum(len(bucket) for bucket in by_type.values())
            for project, by_type in sorted(projects.items())
        },
        "total_nodes": len(nodes),
        "files_written": files_written,
    }
